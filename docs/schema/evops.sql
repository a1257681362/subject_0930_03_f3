-- ========================================================================
-- museum-3 修复材料批号与用量核算
--   设计要点：
--   1) 颜料/黏合剂/保护剂按批号入库（t_material_batch），批号全库唯一；
--      库存按批号行管理，领用只扣批号库存，材料目录信息变更不影响历史工单。
--   2) 工单领用（t_material_usage + 明细行）逐行记录批号、计划/实际用量、
--      部位与操作者；明细行对批号、操作者、部位做不可变快照。
--   3) 过期批号不能领用；同批号重复入库累加库存并写入库流水。
--   4) 退料（t_material_return）必须关联原领用单，库存加回原批号；
--      退料不覆盖、不删除原领用事实，只追加。
--   5) 计划用量与实际用量差异超过阈值（默认 20%）的明细行进入待复核，
--      由定时任务幂等扫描（重启安全）：同一行只产生一条复核记录、
--      一条台账流水，不重复写记录；复核确认后闭环解除。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 12. 材料目录：颜料 / 黏合剂 / 保护剂
--     category: PIGMENT 颜料 / ADHESIVE 黏合剂 / PROTECTANT 保护剂
--     status:   ACTIVE 在用 / DISABLED 停用（停用不影响历史领用事实）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_no      VARCHAR(40)  NOT NULL,
    name             VARCHAR(128) NOT NULL,
    category         VARCHAR(16)  NOT NULL,
    unit             VARCHAR(16)  NOT NULL,
    spec             VARCHAR(255),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_material_no UNIQUE (material_no),
    CONSTRAINT ck_material_category CHECK (category IN ('PIGMENT', 'ADHESIVE', 'PROTECTANT')),
    CONSTRAINT ck_material_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- ------------------------------------------------------------------------
-- 13. 材料批号库存：同材料同批号重复入库累加 stock_qty，批号全库唯一
--     status: IN_STOCK 在库 / EXHAUSTED 用尽 / DISPOSED 报废（不物理删除）
--     过期判定：expire_date 早于当前日期即不可领用
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_batch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id      BIGINT NOT NULL,
    batch_no         VARCHAR(40)  NOT NULL,
    stock_qty        DECIMAL(14,3) NOT NULL DEFAULT 0,
    inbound_qty      DECIMAL(14,3) NOT NULL DEFAULT 0,
    produced_date    DATE,
    expire_date      DATE,
    supplier         VARCHAR(128),
    inbound_at       TIMESTAMP NOT NULL,
    inbound_by       VARCHAR(64),
    status           VARCHAR(16) NOT NULL DEFAULT 'IN_STOCK',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_material_batch_no UNIQUE (batch_no),
    CONSTRAINT ck_material_batch_status CHECK (status IN ('IN_STOCK', 'EXHAUSTED', 'DISPOSED')),
    CONSTRAINT ck_batch_stock_nonneg CHECK (stock_qty >= 0)
);
CREATE INDEX IF NOT EXISTS idx_batch_material ON t_material_batch (material_id);

-- 入库流水：每次（含同批号追加入库）追加一行，库存来源可追溯
CREATE TABLE IF NOT EXISTS t_material_inbound (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id         BIGINT NOT NULL,
    material_id      BIGINT NOT NULL,
    qty              DECIMAL(14,3) NOT NULL,
    supplier         VARCHAR(128),
    inbound_at       TIMESTAMP NOT NULL,
    inbound_by       VARCHAR(64),
    create_by        BIGINT,
    create_time      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inbound_batch ON t_material_inbound (batch_id);

-- ------------------------------------------------------------------------
-- 14. 工单材料领用单：一次领用一张单，含至少一条明细
--     status: ISSUED 已领用 / RETURNED 已退料（整单退齐；部分退料仍为 ISSUED）
--     variance_flag: 0 无超阈值差异 / 1 存在超阈值差异（待复核）
--     review_status: NONE 无需复核 / PENDING 待复核 / CONFIRMED 复核确认
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_usage (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_no         VARCHAR(40) NOT NULL,
    project_id       BIGINT NOT NULL,
    relic_id         BIGINT NOT NULL,
    usage_at         TIMESTAMP NOT NULL,
    status           VARCHAR(16) NOT NULL DEFAULT 'ISSUED',
    variance_flag    INT NOT NULL DEFAULT 0,
    review_status    VARCHAR(16) NOT NULL DEFAULT 'NONE',
    note             VARCHAR(500),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_usage_no UNIQUE (usage_no),
    CONSTRAINT ck_usage_status CHECK (status IN ('ISSUED', 'RETURNED')),
    CONSTRAINT ck_usage_review CHECK (review_status IN ('NONE', 'PENDING', 'CONFIRMED')),
    CONSTRAINT ck_usage_variance CHECK (variance_flag IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_usage_project ON t_material_usage (project_id);

-- 领用明细行：批号、计划/实际用量、部位、操作者在领用时固化为不可变快照；
-- 材料目录或批号之后发生任何变更都不影响本行保存的历史事实。
CREATE TABLE IF NOT EXISTS t_material_usage_line (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_id         BIGINT NOT NULL,
    batch_id         BIGINT NOT NULL,
    material_id      BIGINT NOT NULL,
    material_name    VARCHAR(128) NOT NULL,
    batch_no         VARCHAR(40)  NOT NULL,
    category         VARCHAR(16)  NOT NULL,
    unit             VARCHAR(16)  NOT NULL,
    plan_qty         DECIMAL(14,3) NOT NULL,
    actual_qty       DECIMAL(14,3) NOT NULL,
    apply_part       VARCHAR(128) NOT NULL,
    operator         VARCHAR(64)  NOT NULL,
    variance_pct     DECIMAL(8,4),
    review_status    VARCHAR(16) NOT NULL DEFAULT 'NONE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT ck_line_review CHECK (review_status IN ('NONE', 'PENDING', 'CONFIRMED')),
    CONSTRAINT ck_line_qty_nonneg CHECK (plan_qty >= 0 AND actual_qty >= 0)
);
CREATE INDEX IF NOT EXISTS idx_line_usage ON t_material_usage_line (usage_id);
CREATE INDEX IF NOT EXISTS idx_line_batch ON t_material_usage_line (batch_id);
CREATE INDEX IF NOT EXISTS idx_line_review ON t_material_usage_line (review_status);

-- ------------------------------------------------------------------------
-- 15. 退料单：必须关联原领用单，库存加回原批号；允许分次退、不允许超领
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_return (

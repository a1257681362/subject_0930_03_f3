-- ------------------------------------------------------------------------
-- 6. 台账流水：借/还/修/验/入藏/撤销的不可变动作留痕
--    action: INTAKE / LOAN_OUT / RETURN / REPAIR_START / REPAIR_STAGE
--            / REPAIR_FINISH / ACCEPT / REVOKE / CANCEL
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic_ledger (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relic_id         BIGINT NOT NULL,
    project_id       BIGINT,
    loan_id          BIGINT,
    action           VARCHAR(24) NOT NULL,
    biz_no           VARCHAR(40),
    summary          VARCHAR(500) NOT NULL,
    occurred_at      TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ledger_relic ON t_relic_ledger (relic_id, occurred_at);

-- ------------------------------------------------------------------------
-- 7. 「博物馆文物修复档案起步」幂等锁：保证起步样本全局只播种一次
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_bootstrap_lock (
    id               INT PRIMARY KEY,
    relic_id         BIGINT NOT NULL,
    project_id       BIGINT NOT NULL,
    bootstrapped_at  TIMESTAMP NOT NULL,
    CONSTRAINT ck_bootstrap_singleton CHECK (id = 1)
);

-- ========================================================================
-- museum-2 文物多角度影像归档
--   设计要点：
--   1) 物理文件按 SHA-256 内容寻址（t_photo_file），同一文件重复上传只新增引用、
--      不再落第二份物理文件；作废只置引用状态，物理文件永不删除。
--   2) 一次拍摄批次（t_photo_batch）保存正面/背面/底部/细部照片，逐张校验
--      分辨率、拍摄时间与摄影者；批量失败要逐张返回原因。
--   3) 不同修复阶段的影像形成新版本（t_relic_image.version_no），版本与已确认
--      事实只追加、不覆盖。
--   4) 权限被收紧时上传停止推进；策略本身留痕（t_permission_policy）。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 8. 物理影像文件：内容寻址，全库唯一一份
--    ref_count 为引用计数，只增不减（作废不删文件，故不减计数）。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_photo_file (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_hash     VARCHAR(64)  NOT NULL,
    storage_path     VARCHAR(500) NOT NULL,
    file_name        VARCHAR(255) NOT NULL,
    content_type     VARCHAR(64),
    file_size        BIGINT       NOT NULL,
    width_px         INT          NOT NULL,
    height_px        INT          NOT NULL,
    shot_at          TIMESTAMP    NOT NULL,
    photographer     VARCHAR(64)  NOT NULL,
    ref_count        INT          NOT NULL DEFAULT 1,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_photo_file_hash UNIQUE (content_hash)
);

-- ------------------------------------------------------------------------
-- 9. 拍摄批次：一次拍摄的正面/背面/底部/细部照片归一批次
--    status: CONFIRMED 已确认（有影像通过校验）/ VOID 已作废
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_photo_batch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no         VARCHAR(40)  NOT NULL,
    relic_id         BIGINT      NOT NULL,
    project_id       BIGINT,
    stage_id         BIGINT,
    shot_location    VARCHAR(128),
    remark           VARCHAR(500),
    total_count      INT         NOT NULL DEFAULT 0,
    failed_count     INT         NOT NULL DEFAULT 0,
    status           VARCHAR(16) NOT NULL DEFAULT 'CONFIRMED',
    void_reason      VARCHAR(255),
    voided_at        TIMESTAMP,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_batch_no UNIQUE (batch_no),
    CONSTRAINT ck_batch_status CHECK (status IN ('CONFIRMED', 'VOID'))
);
CREATE INDEX IF NOT EXISTS idx_batch_relic ON t_photo_batch (relic_id);

-- ------------------------------------------------------------------------
-- 10. 文物影像版本引用：一张照片一行，归属批次与版本
--     view_type: FRONT 正面 / BACK 背面 / BOTTOM 底部 / DETAIL 细部
--     status:    ACTIVE 有效 / VOID 已作废（不删行、不删物理文件）
--     同一修复阶段内同一视角复用物理文件只新增引用；不同修复阶段必须新开版本。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic_image (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relic_id         BIGINT      NOT NULL,
    batch_id         BIGINT      NOT NULL,
    file_id          BIGINT      NOT NULL,
    project_id       BIGINT,
    stage_id         BIGINT,
    version_no       INT         NOT NULL,
    view_type        VARCHAR(16) NOT NULL,
    photographer     VARCHAR(64) NOT NULL,
    shot_at          TIMESTAMP   NOT NULL,
    width_px         INT         NOT NULL,
    height_px        INT         NOT NULL,
    status           VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    void_reason      VARCHAR(255),
    voided_at        TIMESTAMP,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT ck_image_view CHECK (view_type IN ('FRONT', 'BACK', 'BOTTOM', 'DETAIL')),
    CONSTRAINT ck_image_status CHECK (status IN ('ACTIVE', 'VOID'))
);
CREATE INDEX IF NOT EXISTS idx_image_relic_ver ON t_relic_image (relic_id, version_no);
CREATE INDEX IF NOT EXISTS idx_image_batch ON t_relic_image (batch_id);
CREATE INDEX IF NOT EXISTS idx_image_file ON t_relic_image (file_id);

-- ------------------------------------------------------------------------
-- 11. 权限策略：文物修复相关操作的收紧开关（单行 id=1，与起步锁同风格）
--     repair_photo_upload_open: 1 允许影像上传，0 收紧（上传停止推进）。
--     收紧只拦截新动作，已确认的影像版本/物理文件/台账事实全部保留。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_permission_policy (
    id                          INT PRIMARY KEY,
    repair_photo_upload_open    INT NOT NULL DEFAULT 1,
    updated_by                  VARCHAR(64),
    updated_at                  TIMESTAMP NOT NULL,
    CONSTRAINT ck_policy_singleton CHECK (id = 1),
    CONSTRAINT ck_policy_upload_flag CHECK (repair_photo_upload_open IN (0, 1))
);

MERGE INTO t_permission_policy (id, repair_photo_upload_open, updated_by, updated_at)
KEY (id)
VALUES (1, 1, 'SYSTEM', CURRENT_TIMESTAMP);

-- ========================================================================
-- museum-3 修复材料批号与用量核算
--   设计要点：
--   1) 颜料(PIGMENT)/黏合剂(ADHESIVE)/保护剂(PROTECTANT) 按【批号】入库
--      （t_material_batch），批号全库唯一；领用扣减 available_qty，
--      过期/耗尽批次只流转状态，不删行，库存流水可追溯。
--   2) 修复工单先做材料计划（t_material_plan，计划用量），实际领用
--      （t_material_issue）记录实际用量、使用部位、操作者；领用行内冗余
--      material_name/batch_no 快照，之后材料批号变更（新批次入库/旧批耗尽）
--      不影响历史工单的展示与核算。
--   3) 退料（t_material_return）必须关联原领用单；一张领用单最多退一次，
--      退料量不超过净领用量；退料在同一事务回补批号可用库存。
--   4) 计划用量与实际用量差异超过阈值（t_material_plan.review_threshold，
--      应用默认 museum.material.review-threshold-percent）时触发复核：
--      登记实际用量即时判定 + 定时任务兜底扫描（t_material_review）。
--   5) 复核任务按 (plan_id, DAT_DIFF) 唯一：定时任务在应用重启后重复扫描
--      也只保留一条复核记录（不重复写），并始终携带领用操作者（不丢操作者）。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 12. 修复材料批号库存
--     category: PIGMENT 颜料 / ADHESIVE 黏合剂 / PROTECTANT 保护剂
--     status:   ACTIVE 在库可用 / EXHAUSTED 已耗尽 / EXPIRED 已过期（不可领用）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_batch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no         VARCHAR(40)  NOT NULL,
    material_name    VARCHAR(128) NOT NULL,
    category         VARCHAR(16)  NOT NULL,
    specification    VARCHAR(128),
    manufacturer     VARCHAR(128),
    unit             VARCHAR(16)  NOT NULL,
    inbound_qty      DECIMAL(14,3) NOT NULL,
    available_qty    DECIMAL(14,3) NOT NULL,
    production_date  DATE,
    inbound_at       TIMESTAMP    NOT NULL,
    expire_date      DATE         NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_material_batch_no UNIQUE (batch_no),
    CONSTRAINT ck_material_category CHECK (category IN ('PIGMENT', 'ADHESIVE', 'PROTECTANT')),
    CONSTRAINT ck_material_batch_status CHECK (status IN ('ACTIVE', 'EXHAUSTED', 'EXPIRED')),
    CONSTRAINT ck_material_qty_nonneg CHECK (available_qty >= 0 AND inbound_qty > 0)
);
CREATE INDEX IF NOT EXISTS idx_material_batch_cat ON t_material_batch (category, status);

-- ------------------------------------------------------------------------
-- 13. 工单材料计划：一个修复项目对一种材料批号的计划用量（可多条）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_plan (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL,
    batch_id         BIGINT NOT NULL,
    planned_qty      DECIMAL(14,3) NOT NULL,
    unit             VARCHAR(16)  NOT NULL,
    -- 差异复核阈值（百分比，如 10 表示实际与计划偏差超过 10% 需复核）；
    -- 为空时使用应用默认阈值
    review_threshold_percent DECIMAL(6,2),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT ck_plan_qty CHECK (planned_qty > 0),
    CONSTRAINT ck_plan_threshold CHECK (review_threshold_percent IS NULL OR review_threshold_percent >= 0)
);
CREATE INDEX IF NOT EXISTS idx_material_plan_project ON t_material_plan (project_id);

-- ------------------------------------------------------------------------
-- 14. 材料领用单：修复工单领用，记录用量、使用部位、操作者
--     status: ISSUED 已领用 / RETURNED 部分或全部退料（状态只用于展示，数量以退料单为准）
--     material_name / batch_no 为领用时刻的不可变快照：
--     之后材料批号变更不影响历史工单。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_issue (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_no         VARCHAR(40)  NOT NULL,
    project_id       BIGINT NOT NULL,
    batch_id         BIGINT NOT NULL,
    plan_id          BIGINT,
    issue_qty        DECIMAL(14,3) NOT NULL,
    actual_qty       DECIMAL(14,3),
    returned_qty     DECIMAL(14,3) NOT NULL DEFAULT 0,
    unit             VARCHAR(16)  NOT NULL,
    apply_part       VARCHAR(255) NOT NULL,
    operator         VARCHAR(64)  NOT NULL,
    material_name    VARCHAR(128) NOT NULL,
    batch_no         VARCHAR(40)  NOT NULL,
    issued_at        TIMESTAMP    NOT NULL,
    used_at          TIMESTAMP,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ISSUED',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_material_issue_no UNIQUE (issue_no),
    CONSTRAINT ck_issue_status CHECK (status IN ('ISSUED', 'RETURNED')),
    CONSTRAINT ck_issue_qty CHECK (issue_qty > 0),
    CONSTRAINT ck_issue_actual CHECK (actual_qty IS NULL OR actual_qty >= 0),
    CONSTRAINT ck_issue_returned CHECK (returned_qty >= 0)
);
CREATE INDEX IF NOT EXISTS idx_material_issue_project ON t_material_issue (project_id);
CREATE INDEX IF NOT EXISTS idx_material_issue_batch ON t_material_issue (batch_id);

-- ------------------------------------------------------------------------
-- 15. 材料退料单：必须关联原领用单（uk_return_issue 一单一退）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_return (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_no        VARCHAR(40)  NOT NULL,
    issue_id         BIGINT NOT NULL,
    project_id       BIGINT NOT NULL,
    batch_id         BIGINT NOT NULL,
    return_qty       DECIMAL(14,3) NOT NULL,
    unit             VARCHAR(16)  NOT NULL,
    operator         VARCHAR(64)  NOT NULL,
    reason           VARCHAR(255),
    returned_at      TIMESTAMP    NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_material_return_no UNIQUE (return_no),
    CONSTRAINT uk_return_issue UNIQUE (issue_id),
    CONSTRAINT ck_return_qty CHECK (return_qty > 0)
);
CREATE INDEX IF NOT EXISTS idx_material_return_project ON t_material_return (project_id);

-- ------------------------------------------------------------------------
-- 16. 用量差异复核任务：计划 vs 实际差异超阈值时生成
--     reason: DAT_DIFF 用量差异超阈值
--     status: PENDING 待复核 / CONFIRMED 已核实 / ADJUSTED 已调整
--     issue_operator 冗余领用操作者：定时任务重启重扫时重新组装也不丢操作者。
--     (plan_id, reason) 唯一保证同一计划同一原因只产生一条复核记录。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_review (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_no        VARCHAR(40)  NOT NULL,
    plan_id          BIGINT NOT NULL,
    project_id       BIGINT NOT NULL,
    issue_id         BIGINT NOT NULL,
    batch_id         BIGINT NOT NULL,
    reason           VARCHAR(24)  NOT NULL,
    planned_qty      DECIMAL(14,3) NOT NULL,
    actual_qty       DECIMAL(14,3) NOT NULL,
    diff_percent     DECIMAL(9,2)  NOT NULL,
    threshold_percent DECIMAL(6,2) NOT NULL,
    apply_part       VARCHAR(255) NOT NULL,

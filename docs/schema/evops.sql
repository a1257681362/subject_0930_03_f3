-- ------------------------------------------------------------------------
-- 16. 用量差异复核：每条超阈值明细行全生命周期只允许一条记录，
--     定时任务凭此天然幂等（重启后重复扫描不会多写记录）。
--     status: OPEN 待复核 / CONFIRMED 已确认
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_material_review (

    actual_qty       DECIMAL(14,3) NOT NULL,
    variance_pct     DECIMAL(8,4) NOT NULL,
    threshold_pct    DECIMAL(8,4) NOT NULL,
    operator         VARCHAR(64) NOT NULL,
    apply_part       VARCHAR(128) NOT NULL,
    status           VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    detected_at      TIMESTAMP NOT NULL,
    confirmed_by     VARCHAR(64),
    confirmed_at     TIMESTAMP,
    confirm_note     VARCHAR(500),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_review_line UNIQUE (line_id),
    CONSTRAINT ck_review_status CHECK (status IN ('OPEN', 'CONFIRMED'))
);
CREATE INDEX IF NOT EXISTS idx_review_status ON t_material_review (status);

